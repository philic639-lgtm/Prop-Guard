// Bundle the on-device account-screenshot reader for iOS / Android.
//   npm run ocr:webview
// The native app runs the SAME reader as the web app (src/services/accountImport/ocr.web.ts:
// tesseract.js, image preparation, redaction) inside a hidden WebView. This script bundles
// src/services/accountImport/webview/entry.ts into one script string and writes
// src/services/accountImport/webview/bundle.generated.ts. Re-run it after changing any of
// the inputs below — a unit test fails when the bundle is out of date.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';

const require = createRequire(import.meta.url);
const { build } = require('esbuild');

const root = process.cwd();
const dir = join(root, 'src', 'services', 'accountImport');
/** Every file whose change requires a rebuild (kept in sync with the drift test). */
export const INPUTS = ['webview/entry.ts', 'ocr.web.ts', 'ocrShared.ts'];

const tesseractVersion = require('tesseract.js/package.json').version;
const hash = createHash('sha256');
for (const f of INPUTS) hash.update(readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n'));
hash.update(`tesseract.js@${tesseractVersion}`);
const sourceHash = hash.digest('hex').slice(0, 16);

const result = await build({
  entryPoints: [join(dir, 'webview', 'entry.ts')],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  target: ['es2020', 'safari15', 'chrome90'], // iOS 15+ WKWebView (Expo SDK 57 minimum) and current Android System WebView
  minify: true,
  legalComments: 'none',
  alias: { '@': join(root, 'src') },
  // No self-hosted asset URLs inside the app: the WebView uses tesseract.js's default CDN
  // (jsDelivr) for the engine and model, exactly like the web app without EXPO_PUBLIC_OCR_ASSETS_URL.
  define: {
    'process.env.EXPO_PUBLIC_OCR_ASSETS_URL': 'undefined',
    'process.env.EXPO_PUBLIC_OCR_LANG_URL': 'undefined',
    'process.env.EXPO_PUBLIC_OCR_RESTRICTED_HOST': 'undefined',
    'process.env.NODE_ENV': '"production"',
  },
});
const js = result.outputFiles[0].text;
writeFileSync(
  join(dir, 'webview', 'bundle.generated.ts'),
  `// GENERATED by scripts/build-ocr-webview.mjs — do not edit. Run \`npm run ocr:webview\`.\n` +
    `export const OCR_WEBVIEW_SOURCE_HASH = '${sourceHash}';\n` +
    `export const OCR_WEBVIEW_TESSERACT = '${tesseractVersion}';\n` +
    `export const OCR_WEBVIEW_JS: string = ${JSON.stringify(js)};\n`,
);
console.log(`ocr webview bundle: ${(js.length / 1024).toFixed(0)} KB, source ${sourceHash}, tesseract.js ${tesseractVersion}`);
