import * as Tesseract from 'tesseract.js';

import type { OcrBox, OcrLine, OcrPage } from '@/lib/engines/accountImport';

import type { ImportImage } from './images';
import { MESSAGES, OcrError, ocrLog, sanitizeDetail, type OcrErrorCode, type OcrProgress } from './ocrShared';

export { OcrError, ocrLog, sanitizeDetail, type OcrErrorCode, type OcrProgress } from './ocrShared';

/**
 * Free, in-browser OCR with tesseract.js (Apache-2.0). The screenshot never
 * leaves the device: only the OCR engine and English model are downloaded
 * (once, then cached by the browser) — from the jsDelivr CDN by default, or
 * from your own host via EXPO_PUBLIC_OCR_ASSETS_URL (see `npm run ocr:assets`).
 */
export const OCR_ENGINE = { id: 'tesseract' as const, label: 'On-device OCR (Tesseract)', free: true };

type TWorker = { recognize: (img: unknown, opts?: object, output?: object) => Promise<{ data: TData }>; terminate: () => Promise<unknown> };
interface TWord { text: string; confidence: number; bbox: OcrBox }
interface TData { confidence: number; blocks: { paragraphs: { lines: { text: string; confidence: number; bbox: OcrBox; words: TWord[] }[] }[] }[] | null }

type CreateWorker = (lang: string, oem: number, options: object) => Promise<TWorker>;
let workerP: Promise<TWorker> | null = null;
let progressCb: ((p: OcrProgress) => void) | null = null;
/** Last sign of life from the OCR worker (download / recognition progress). */
let lastActivity = 0;

const fail = (code: OcrErrorCode, cause?: unknown) => new OcrError(code, MESSAGES[code], sanitizeDetail(cause));

/** Overall limit for download + start-up (~7 MB on first use). */
const LOAD_MS = 90_000;
/** Overall limit for recognising one prepared image. */
const READ_MS = 90_000;
/** Inactivity limit: no bytes / no progress from the worker for this long = stalled. */
const STALL_MS = 30_000;

export function ocrAvailable(): boolean {
  return typeof document !== 'undefined' && typeof Worker !== 'undefined' && typeof WebAssembly !== 'undefined';
}

/**
 * Absolute URL (the OCR worker cannot resolve relative paths). Relative paths
 * are relative to the app root — a page's <base> when it sets one — never to
 * the current route ("/accounts/import" + "ocr" must not become "/accounts/ocr").
 */
const absolute = (raw: string) => {
  const root = document.querySelector('base[href]') ? document.baseURI : `${location.origin}/`;
  return new URL(raw.endsWith('/') ? raw : `${raw}/`, root).href.replace(/\/$/, '');
};

/** tesseract.js's default model location when nothing is self-hosted. */
const CDN_LANG = 'https://cdn.jsdelivr.net/npm/@tesseract.js-data/eng/4.0.0_best_int';

/**
 * Where the worker, WASM core and English model come from. Self-hosting all
 * three on the app's own origin (`EXPO_PUBLIC_OCR_ASSETS_URL`) is the only
 * setup that works in sandboxed / CSP-restricted pages.
 *
 * `EXPO_PUBLIC_OCR_RESTRICTED_HOST=true` is for hosts that only serve web file
 * types (no `.gz`, e.g. sandboxed preview hosts): the model is published as
 * `lang/eng.traineddata.wasm` and the worker starts through `pg-worker.js`,
 * which sends tesseract.js's fixed `eng.traineddata.gz` request to that file
 * (both generated by `npm run ocr:assets`).
 */
export function ocrAssets() {
  const raw = process.env.EXPO_PUBLIC_OCR_ASSETS_URL;
  const lang = process.env.EXPO_PUBLIC_OCR_LANG_URL;
  const restricted = process.env.EXPO_PUBLIC_OCR_RESTRICTED_HOST === 'true';
  const base = raw ? absolute(raw) : null;
  const langPath = lang ? absolute(lang) : base ? `${base}/lang` : CDN_LANG;
  const sameOrigin = !!base && new URL(base).origin === location.origin;
  const viaBootstrap = restricted && sameOrigin;
  const options: Record<string, unknown> = { gzip: true, langPath };
  // A same-origin worker file needs no blob: worker (often blocked by CSP).
  if (base) Object.assign(options, { workerPath: `${base}/${viaBootstrap ? 'pg-worker.js' : 'worker.min.js'}`, corePath: `${base}/core`, workerBlobURL: !sameOrigin });
  return { options, modelUrl: `${langPath}/eng.traineddata.${viaBootstrap ? 'wasm' : 'gz'}` };
}

/**
 * Download the language model on the page (inactivity + overall timeout,
 * real byte progress, clear errors); the worker then gets it from the browser
 * cache. tesseract.js itself never reports a failed model download.
 */
let modelReady: Promise<void> | null = null;
async function fetchModel(url: string): Promise<void> {
  const ctrl = new AbortController();
  const started = Date.now();
  let last = Date.now();
  let why: string | null = null;
  // Settles the moment we give up, even if the network layer never reacts to the abort.
  let giveUp: (e: unknown) => void = () => undefined;
  const gaveUp = new Promise<never>((_, reject) => {
    giveUp = reject;
  });
  gaveUp.catch(() => undefined);
  const timer = setInterval(() => {
    if (Date.now() - last > STALL_MS) why = `no data for ${STALL_MS / 1000} s`;
    else if (Date.now() - started > LOAD_MS) why = `not finished after ${LOAD_MS / 1000} s`;
    if (why) {
      ctrl.abort();
      giveUp(new Error('aborted'));
    }
  }, 1000);
  try {
    let resp: Response;
    try {
      resp = await Promise.race([fetch(url, { signal: ctrl.signal, cache: 'force-cache' }), gaveUp]);
    } catch (e) {
      throw ctrl.signal.aborted ? fail('load_timeout', why) : fail('load_blocked', e);
    }
    if (!resp.ok) throw fail(resp.status === 404 ? 'load_missing' : 'load_blocked', `HTTP ${resp.status}`);
    const total = Number(resp.headers.get('content-length')) || null;
    let got = 0;
    progressCb?.({ stage: 'downloading_model', received: 0, total });
    try {
      const reader = resp.body?.getReader();
      if (reader) {
        for (;;) {
          const { done, value } = await Promise.race([reader.read(), gaveUp]);
          if (done) break;
          got += value.byteLength;
          last = lastActivity = Date.now();
          progressCb?.({ stage: 'downloading_model', received: got, total });
        }
      } else got = (await Promise.race([resp.arrayBuffer(), gaveUp])).byteLength;
    } catch (e) {
      throw ctrl.signal.aborted ? fail('load_timeout', why) : fail('load_blocked', e);
    }
    // A host error page or a truncated file is not a 3 MB model.
    if (got < 500_000) throw fail('load_missing', `model file is only ${Math.round(got / 1024)} KB`);
    ocrLog('model: downloaded', { ms: Date.now() - started, kb: Math.round(got / 1024) });
  } finally {
    clearInterval(timer);
  }
}

/**
 * Reject when `p` does not settle in `totalMs` (overall timeout), or when the
 * worker shows no activity for `stallMs` (inactivity timeout).
 */
function guard<T>(p: Promise<T>, totalMs: number, stallMs: number, code: OcrErrorCode): Promise<T> {
  lastActivity = Date.now();
  const started = Date.now();
  let timer: ReturnType<typeof setInterval> | undefined;
  const watchdog = new Promise<never>((_, reject) => {
    timer = setInterval(() => {
      const now = Date.now();
      if (now - started > totalMs) reject(fail(code, `not finished after ${Math.round(totalMs / 1000)} s`));
      else if (now - lastActivity > stallMs) reject(fail(code, `no progress for ${Math.round(stallMs / 1000)} s`));
    }, 1000);
  });
  return Promise.race([p, watchdog]).finally(() => clearInterval(timer));
}

/** Drop a broken or stuck worker so the next attempt starts clean. */
function dropWorker() {
  const w = workerP;
  workerP = null;
  if (w) void w.then((x) => x.terminate()).catch(() => undefined);
}

/** tesseract.js's createWorker (replaceable in tests). */
let createWorkerImpl: CreateWorker = (...args) => {
  const T = Tesseract as unknown as { createWorker?: CreateWorker; default?: { createWorker: CreateWorker } };
  return (T.createWorker ?? T.default!.createWorker)(...args);
};
/** Test hook: swap tesseract.js and reset module state. */
export function __setOcrTestHooks(hooks: { createWorker?: (lang: string, oem: number, options: never) => Promise<unknown>; reset?: boolean }) {
  if (hooks.createWorker) createWorkerImpl = hooks.createWorker as unknown as CreateWorker;
  if (hooks.reset) {
    workerP = null;
    modelReady = null;
  }
}

/** Load (or reuse) the OCR worker: model download → engine start-up, each with timeouts and real errors. */
export async function prepareOcr(onProgress?: (p: OcrProgress) => void): Promise<void> {
  const prev = progressCb;
  if (onProgress) progressCb = onProgress;
  try {
    await getWorker();
  } finally {
    progressCb = prev;
  }
}

async function getWorker(): Promise<TWorker> {
  if (!workerP) {
    const t0 = Date.now();
    ocrLog('engine: loading');
    progressCb?.({ stage: 'loading_engine' });
    const { options, modelUrl } = ocrAssets();
    let ready = false;
    let rejectInit: (e: OcrError) => void = () => undefined;
    // tesseract.js swallows a failed model load / initialisation (its start-up
    // promise then never settles) and only reports it to `errorHandler`.
    const initFailed = new Promise<never>((_, reject) => {
      rejectInit = reject;
    });
    const start = async (): Promise<TWorker> => {
      modelReady ??= fetchModel(modelUrl).catch((e) => {
        modelReady = null;
        throw e;
      });
      await modelReady;
      progressCb?.({ stage: 'starting_engine' });
      let created: Promise<TWorker>;
      try {
        // The JS wrapper is small (~18 KB); the WASM engine loads here, on first use.
        created = createWorkerImpl('eng', 1, {
          ...options,
          logger: (m: { status: string; progress: number }) => {
            lastActivity = Date.now();
            if (m.status === 'recognizing text') progressCb?.({ stage: 'recognizing', fraction: Number.isFinite(m.progress) ? m.progress : null });
          },
          errorHandler: (err: unknown) => {
            if (!ready) rejectInit(fail('load_failed', err));
            // After start-up: a broken worker is replaced on the next read.
            else dropWorker();
          },
        });
      } catch (e) {
        throw fail('load_failed', e); // e.g. workers blocked by the page's security policy
      }
      created.catch(() => undefined);
      return Promise.race([created, initFailed]).catch((e) => {
        void created.then((w) => w.terminate()).catch(() => undefined);
        throw e instanceof OcrError ? e : fail('load_failed', e);
      });
    };
    const p = guard(start(), LOAD_MS, LOAD_MS, 'load_timeout').catch((e) => {
      throw e instanceof OcrError ? e : fail('load_failed', e);
    });
    workerP = p;
    p.then(
      () => {
        ready = true;
        ocrLog('engine: ready', { ms: Date.now() - t0 });
      },
      (e: OcrError) => {
        ocrLog('engine: failed', { code: e.code, detail: e.detail, ms: Date.now() - t0 });
        if (workerP === p) workerP = null;
      },
    );
  }
  return workerP;
}

/** Recognise an already prepared image (exported for tests). */
export async function recognizePrepared(input: unknown, onProgress?: (p: OcrProgress) => void): Promise<TData> {
  const prev = progressCb;
  if (onProgress) progressCb = onProgress;
  try {
    const worker = await getWorker();
    progressCb?.({ stage: 'recognizing', fraction: null });
    try {
      const { data } = await guard(worker.recognize(input, {}, { blocks: true, text: false }), READ_MS, STALL_MS, 'read_timeout');
      return data;
    } catch (e) {
      // A stuck or crashed worker would block every later read: start fresh next time.
      dropWorker();
      throw e instanceof OcrError ? e : fail('read_failed', e);
    }
  } finally {
    progressCb = prev;
  }
}

function loadImage(src: string): Promise<HTMLImageElement> {
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.onload = () => resolve(img);
    img.onerror = () => reject(fail('image_failed', 'the browser could not decode this file'));
    img.src = src;
  });
}

/** Most pixels we hand to OCR (memory on phones, time on slow devices). */
const MAX_PIXELS = 10_000_000;

/**
 * Upscale factor. Desktop screenshots at normal resolution have ~11–13 px
 * labels, too small for Tesseract — double them. Retina / 4K captures and
 * phone screenshots (already 2–3× pixels) stay at native size.
 */
export function ocrScale(w: number, h: number): number {
  const portrait = h > w * 1.3;
  let s = w >= 2400 || (portrait && w >= 900) ? 1 : w <= 1000 ? 2.5 : 2;
  s = Math.min(s, Math.sqrt(MAX_PIXELS / Math.max(1, w * h)));
  return Math.max(0.5, Math.round(s * 100) / 100);
}

/**
 * Scale of the second reading of the same image, or null. A phone PHOTO of a screen is a large
 * image with small text (read at 1× by `ocrScale`, which assumes a screenshot); a desktop capture
 * is upscaled. Reading at a second scale and comparing catches the digits one scale misreads
 * ("$25,300" vs "$25,390") — disagreements become conflicts, never a silent choice.
 */
export function secondScale(w: number, h: number, first: number): number | null {
  const cap = Math.sqrt(MAX_PIXELS / Math.max(1, w * h));
  const s = Math.round((first <= 1.2 ? Math.min(1.6, cap) : 1) * 100) / 100;
  return Math.abs(s - first) >= 0.3 ? s : null;
}

/**
 * Prepare for OCR: rescale (see `ocrScale`), grayscale, invert dark themes
 * (dark dashboards read better as dark-on-light) and stretch contrast.
 */
function preprocess(img: HTMLImageElement, at?: number): { canvas: HTMLCanvasElement; scale: number; dark: boolean } {
  const w0 = img.naturalWidth || img.width;
  const h0 = img.naturalHeight || img.height;
  const scale = at ?? ocrScale(w0, h0);
  const canvas = document.createElement('canvas');
  canvas.width = Math.round(w0 * scale);
  canvas.height = Math.round(h0 * scale);
  const ctx = canvas.getContext('2d', { willReadFrequently: true })!;
  ctx.imageSmoothingQuality = 'high';
  ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
  const data = ctx.getImageData(0, 0, canvas.width, canvas.height);
  const px = data.data;
  let sum = 0;
  let lo = 255;
  let hi = 0;
  const gray = new Uint8ClampedArray(px.length / 4);
  for (let i = 0, j = 0; i < px.length; i += 4, j++) {
    // Max channel keeps coloured text (green / red P&L) as bright as white text on dark themes.
    const g = Math.max(0.299 * px[i] + 0.587 * px[i + 1] + 0.114 * px[i + 2], 0.85 * Math.max(px[i], px[i + 1], px[i + 2]));
    gray[j] = g;
    sum += g;
  }
  const dark = sum / gray.length < 110;
  for (let j = 0; j < gray.length; j++) {
    const g = dark ? 255 - gray[j] : gray[j];
    gray[j] = g;
    if (g < lo) lo = g;
    if (g > hi) hi = g;
  }
  const range = Math.max(1, hi - lo);
  for (let i = 0, j = 0; i < px.length; i += 4, j++) {
    const v = ((gray[j] - lo) * 255) / range;
    px[i] = px[i + 1] = px[i + 2] = v;
  }
  ctx.putImageData(data, 0, 0);
  return { canvas, scale, dark };
}

const unscale = (b: OcrBox, s: number): OcrBox => ({ x0: Math.round(b.x0 / s), y0: Math.round(b.y0 / s), x1: Math.round(b.x1 / s), y1: Math.round(b.y1 / s) });

function toPage(data: TData, img: HTMLImageElement, scale: number): OcrPage {
  const lines: OcrLine[] = [];
  for (const b of data.blocks ?? [])
    for (const p of b.paragraphs)
      for (const l of p.lines) {
        const words = l.words.filter((w) => w.text.trim()).map((w) => ({ text: w.text.trim(), confidence: Math.round(w.confidence), bbox: unscale(w.bbox, scale) }));
        if (words.length) lines.push({ text: l.text.trim(), confidence: Math.round(l.confidence), bbox: unscale(l.bbox, scale), words });
      }
  return { width: img.naturalWidth, height: img.naturalHeight, confidence: Math.round(data.confidence), lines };
}

/** Read the image at its OCR scale and, when useful, at a second scale (`OcrPage.passes`). */
export async function recognize(image: ImportImage, onProgress?: (p: OcrProgress) => void): Promise<OcrPage> {
  const t0 = Date.now();
  try {
    const img = await loadImage(image.uri);
    const { canvas, scale, dark } = preprocess(img);
    ocrLog('image: prepared', { width: img.naturalWidth, height: img.naturalHeight, scale, dark });
    const page = toPage(await recognizePrepared(canvas, onProgress), img, scale);
    const s2 = secondScale(img.naturalWidth, img.naturalHeight, scale);
    if (s2 != null) {
      try {
        page.passes = [toPage(await recognizePrepared(preprocess(img, s2).canvas, onProgress), img, s2)];
      } catch (e) {
        // The first reading stands on its own; a failed second pass only means nothing to compare.
        ocrLog('image: second pass failed', { code: e instanceof OcrError ? e.code : 'unknown', scale: s2 });
      }
    }
    const words = page.lines.reduce((n, l) => n + l.words.length, 0);
    ocrLog('image: read', { totalMs: Date.now() - t0, lines: page.lines.length, words, confidence: page.confidence, passes: 1 + (page.passes?.length ?? 0) });
    return page;
  } catch (e) {
    ocrLog('image: failed', { code: e instanceof OcrError ? e.code : 'unknown', detail: e instanceof OcrError ? e.detail : sanitizeDetail(e), ms: Date.now() - t0 });
    throw e instanceof OcrError ? e : fail('read_failed', e);
  }
}

export async function disposeOcr(): Promise<void> {
  dropWorker();
}

/** Black out regions on a copy of the image (account numbers, emails) before preview or sending. */
export async function redactImage(image: ImportImage, boxes: OcrBox[]): Promise<{ uri: string; base64: string } | null> {
  const img = await loadImage(image.uri);
  const canvas = document.createElement('canvas');
  const maxW = 1600;
  const s = Math.min(1, maxW / img.naturalWidth);
  canvas.width = Math.round(img.naturalWidth * s);
  canvas.height = Math.round(img.naturalHeight * s);
  const ctx = canvas.getContext('2d')!;
  ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
  ctx.fillStyle = '#000';
  for (const b of boxes) ctx.fillRect((b.x0 - 4) * s, (b.y0 - 4) * s, (b.x1 - b.x0 + 8) * s, (b.y1 - b.y0 + 8) * s);
  const uri = canvas.toDataURL('image/jpeg', 0.85);
  return { uri, base64: uri.slice(uri.indexOf(',') + 1) };
}
