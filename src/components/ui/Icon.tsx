export type IconName = keyof typeof ICONS;

/** Names drawn filled (dots, selected stars, stop squares) — everything else is a consistent outline. */
const FILLED = new Set<IconName>(['ellipse', 'star', 'stop', 'pause', 'play']);

export interface IconProps {
  name: IconName;
  size?: number;
  color?: string;
  /** Line weight (Lucide default 2; the app uses 2 at 20–24px, 1.75 for large spot icons). */
  strokeWidth?: number;
  style?: StyleProp<ViewStyle>;
  /** When set, the icon is announced (otherwise decorative). */
  accessibilityLabel?: string;
}

export function Icon({ name, size = 20, color = 'currentColor', strokeWidth, style, accessibilityLabel }: IconProps) {
  const Glyph: LucideIcon = ICONS[name] ?? CircleHelp;
  const filled = FILLED.has(name);
  return (
    <Glyph
      size={size}
      color={color}
      strokeWidth={strokeWidth ?? (size >= 28 ? 1.75 : 2)}
      fill={filled ? color : 'none'}
      style={style}
      {...(accessibilityLabel
        ? { accessible: true, accessibilityRole: 'image' as const, accessibilityLabel }
        : { accessibilityElementsHidden: true, importantForAccessibility: 'no-hide-descendants' as const })}
    />
  );
}

